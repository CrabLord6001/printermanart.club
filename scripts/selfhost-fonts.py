"""Replace Google Fonts with self-hosted copies, without changing how pages render.

Google serves a different cut of a variable family depending on which weights a
page asks for, so a single shared stylesheet shifts glyph metrics on some pages
(enough to re-wrap a heading). This keeps each distinct request as its own small
stylesheet and lets them share the woff2 files, which are stored under their
Google hash name so identical files dedupe across sets.

Run from the repo root with the site served locally on $PORT (default 8081):
    python3 scripts/selfhost-fonts.py --apply
"""
import asyncio, json, pathlib, re, sys, collections, urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
SKIP = {".git"}
# No Greek, Cyrillic or Vietnamese text anywhere on this site, so those
# subsets would be bytes in the repo that no visitor ever downloads.
KEEP_SUBSETS = {"latin", "latin-ext"}
FONTDIR = ROOT / "fonts" / "google"
APPLY = "--apply" in sys.argv

GOOGLE_LINE = re.compile(
    r'^\s*(?:<noscript>)?<link[^>]*(?:fonts\.googleapis\.com|fonts\.gstatic\.com)[^>]*>'
    r'(?:</noscript>)?\s*$', re.I)
CSS_URL = re.compile(r'https://fonts\.googleapis\.com/css2?\?[^"\']+')


def pages():
    for p in sorted(ROOT.rglob("*.html")):
        if any(x in SKIP for x in p.relative_to(ROOT).parts):
            continue
        yield p


def page_requests(text):
    """Every Google Fonts stylesheet a page asks for. Some pages load two —
    a body face and a display face — and taking only the first drops one."""
    seen, out = set(), []
    for m in CSS_URL.finditer(text):
        u = m.group(0).replace("&amp;", "&")
        if u not in seen:
            seen.add(u)
            out.append(u)
    return tuple(out)


async def fetch_css(urls):
    """Fetch each stylesheet as a real browser, so Google serves the same cut
    the site's visitors get rather than a curl-shaped fallback."""
    from playwright.async_api import async_playwright
    out = {}
    async with async_playwright() as pw:
        b = await pw.chromium.launch(executable_path="/usr/bin/google-chrome",
                                     args=["--no-sandbox"])
        pg = await b.new_page()
        for u in urls:
            r = await pg.goto(u)
            out[u] = await r.text()
        await b.close()
    return out


def main():
    reqs = collections.OrderedDict()
    page_map = {}
    for p in pages():
        t = p.read_text(encoding="utf-8")
        u = page_requests(t)
        if u:
            reqs.setdefault(u, len(reqs))
            page_map[p] = u
    all_urls = sorted({u for key in reqs for u in key})
    print(f"{len(page_map)} pages, {len(reqs)} distinct font requests "
          f"({len(all_urls)} stylesheets to fetch)")

    css_by_url = asyncio.run(fetch_css(all_urls))

    FONTDIR.mkdir(parents=True, exist_ok=True)
    downloaded = {}
    sheets = {}

    for key, idx in reqs.items():
        faces = []
        for url in key:
            faces += re.findall(r"/\* (\S+) \*/\s*(@font-face \{[^}]+\})", css_by_url[url])
        rules = []
        for subset, body in faces:
            if subset not in KEEP_SUBSETS:
                continue
            src = re.search(r"url\((https://[^)]+)\)", body).group(1)
            name = src.rsplit("/", 1)[-1]
            if name not in downloaded:
                dest = FONTDIR / name
                if not dest.exists():
                    dest.write_bytes(urllib.request.urlopen(src, timeout=60).read())
                downloaded[name] = dest.stat().st_size
            rules.append(" ".join(body.split()).replace(src, f"/fonts/google/{name}"))
        sheets[key] = f"fonts/set-{idx + 1}.css"
        if APPLY:
            fams = sorted({re.search(r"font-family: '([^']+)'", r).group(1) for r in rules})
            hdr = (f"/* Self-hosted Google Fonts (SIL Open Font License). Generated by\n"
                   f"   scripts/selfhost-fonts.py — do not hand-edit.\n"
                   f"   Families: {', '.join(fams)}\n"
                   f"   Subsets: latin, latin-ext.\n"
                   f"   Matches the exact cut Google served for this page's weight set,\n"
                   f"   so glyph metrics are unchanged. */\n\n")
            (ROOT / sheets[key]).write_text(hdr + "\n".join(rules) + "\n")

    total = sum(downloaded.values())
    print(f"{len(downloaded)} woff2 files, {total // 1024} kB total")
    for k, s in sheets.items():
        n = sum(1 for _ in re.finditer("@font-face", (ROOT / s).read_text())) if APPLY else 0
        fams = len({u for u in k})
        print(f"  {s}  ({n} faces, {fams} stylesheet(s) merged)"
              f"  <- {len([p for p, kk in page_map.items() if kk == k])} pages")

    changed = 0
    for p, key in page_map.items():
        text = p.read_text(encoding="utf-8")
        lines, out, first = text.split("\n"), [], None
        for ln in lines:
            if GOOGLE_LINE.match(ln):
                if first is None:
                    first = True
                    indent = re.match(r"\s*", ln).group(0)
                    out.append(f'{indent}<link rel="stylesheet" href="/{sheets[key]}" />')
                continue
            out.append(ln)
        new = "\n".join(out)
        if "fonts.googleapis.com" in new or "fonts.gstatic.com" in new:
            print(f"  LEFTOVER, skipped: {p.relative_to(ROOT)}")
            continue
        changed += 1
        if APPLY:
            p.write_text(new, encoding="utf-8")
    print(f"{'rewrote' if APPLY else 'would rewrite'} {changed} pages")


main()
